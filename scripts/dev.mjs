import { createServer } from 'vite';
import { build } from 'esbuild';
import { spawn } from 'node:child_process';
import electron from 'electron';
await build({entryPoints:['electron/main.ts'],bundle:true,platform:'node',format:'cjs',outfile:'dist-electron/main.cjs',external:['electron','ffmpeg-static','ffprobe-static']});
await build({entryPoints:['electron/preload.ts'],bundle:true,platform:'node',format:'cjs',outfile:'dist-electron/preload.cjs',external:['electron']});
const server=await createServer({server:{host:'127.0.0.1',port:5173,strictPort:true}});
await server.listen();
const child=spawn(electron,['.'],{stdio:'inherit',env:{...process.env,LUMEN_DEV_URL:'http://127.0.0.1:5173'}});
child.once('exit',async code=>{await server.close();process.exit(code??0);});
process.once('SIGINT',()=>child.kill());
